#!/usr/bin/env node
/* Builds config.js from .env (local) or process.env (Vercel / Netlify / CI).
   No dependencies. Only whitelisted keys are exported, so nothing else leaks
   into the browser. Run:  node scripts/generate-config.js                   */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

// key -> { required, default }
const SCHEMA = {
  WEB3FORMS_ACCESS_KEY: { required: true },
  CONTACT_MAX_PER_DAY:  { default: "10" },
  CONTACT_EMAIL:        { default: "" },
  SITE_URL:             { default: "" },
  APP_ENV:              { default: "development" }
};

function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const i = line.indexOf("=");
    if (i < 1) continue;
    let v = line.slice(i + 1).trim();
    if (/^(['"]).*\1$/.test(v)) v = v.slice(1, -1);
    out[line.slice(0, i).trim()] = v;
  }
  return out;
}

const envFile = path.join(ROOT, ".env");
const fromFile = fs.existsSync(envFile) ? parseEnv(fs.readFileSync(envFile, "utf8")) : {};

const cfg = {};
const problems = [];
for (const [key, rule] of Object.entries(SCHEMA)) {
  // real environment (hosting dashboard) wins over .env
  let v = process.env[key] !== undefined ? process.env[key] : fromFile[key];
  if (v === undefined || v === "") v = rule.default || "";
  if (rule.required && !v) problems.push(key);
  cfg[key] = v;
}

cfg.CONTACT_MAX_PER_DAY = Number(cfg.CONTACT_MAX_PER_DAY) || 10;

if (problems.length) {
  const msg = "Missing: " + problems.join(", ") + " (set in .env or your host's env settings)";
  if (cfg.APP_ENV === "production") { console.error("ERROR " + msg); process.exit(1); }
  console.warn("WARNING " + msg);
}

const out =
  "/* AUTO-GENERATED by scripts/generate-config.js. Do not edit; do not commit. */\n" +
  "window.ENV = Object.freeze(" + JSON.stringify(cfg, null, 2) + ");\n";

fs.writeFileSync(path.join(ROOT, "assets", "js", "config.js"), out);
console.log("assets/js/config.js written (" + Object.keys(cfg).length + " keys, " + cfg.APP_ENV + ")");
